const assert = require('node:assert/strict');
const { contenuPublic } = require('../lib/contenu-public');
const defauts = require('../app/defaults.json');
const secours = require('../assets/data/site.json');
const textes = require('../lib/recrutement-public.json');
const original = structuredClone(defauts.contenu);
const destinataire = original.travaillerAvecNous.emailDestination;
const ancienne = structuredClone(original);
ancienne.travaillerAvecNous.texte = `Nous recrutons régulièrement : contactez ${destinataire}`;
ancienne.travaillerAvecNous.formulaire.sousTitre = `Dossier transmis à ${destinataire.toUpperCase()}`;
ancienne.travaillerAvecNous.googleForm.actionUrl = 'https://docs.google.com/forms/d/e/exemple/formResponse';
ancienne.pied.description = `Écrire à ${destinataire.toUpperCase()}`;
const avant = JSON.stringify(ancienne);
const public = contenuPublic(ancienne);
assert.ok(!JSON.stringify(public).toLowerCase().includes(destinataire.toLowerCase()));
assert.equal(public.travaillerAvecNous.texte, textes.texte);
assert.equal(public.travaillerAvecNous.formulaire.sousTitre, textes.sousTitre);
assert.deepEqual(public.travaillerAvecNous.googleForm, {actionUrl: ancienne.travaillerAvecNous.googleForm.actionUrl});
assert.equal(public.travaillerAvecNous.emailDestination, undefined);
assert.equal(JSON.stringify(ancienne), avant, 'aucune mutation des réglages privés');
assert.equal(original.travaillerAvecNous.emailDestination, destinataire, 'réception conservée');
assert.equal(public.identite.email, original.identite.email, 'contact professionnel public conservé');
const personnalise = structuredClone(original);
personnalise.travaillerAvecNous.emailDestination = 'rh-prive@example.invalid';
personnalise.travaillerAvecNous.texte = 'Envoyez vos informations à rh-prive@example.invalid';
assert.ok(!JSON.stringify(contenuPublic(personnalise)).includes('rh-prive@example.invalid'));
assert.equal(contenuPublic(original).travaillerAvecNous.texte, original.travaillerAvecNous.texte);
assert.ok(!JSON.stringify(secours).includes(destinataire));
assert.equal(secours.contenu.travaillerAvecNous.emailDestination, undefined);
assert.equal(secours.contenu.travaillerAvecNous.googleForm.gmailDestination, undefined);
console.log('OK : textes, anciens contenus, API publique et secours sans adresse privée ; configuration serveur inchangée.');
